"""Build small ontology "slims" for offline tests.

For every OBO term (CURIE) used in examples/valid/*.yaml and in
mappings/curated/*.sssom.tsv, walk its is_a parents up to the root using the
EBI OLS4 API and write rdfs:subClassOf + rdfs:label triples to
examples/ontology-slims/<prefix>.ttl.

Why: pyoxigraph does no reasoning, so queries use rdfs:subClassOf* paths.
Committing slims keeps tests offline and avoids downloading full ontologies
(NCBITaxon alone is several GB). Re-run with `make slims` after adding terms.
"""

from __future__ import annotations

import json
import re
import sys
import time
import urllib.parse
import urllib.request
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "examples" / "ontology-slims"
OLS = "https://www.ebi.ac.uk/ols4/api"
OBO = "http://purl.obolibrary.org/obo/"

# prefix -> OLS ontology id
ONTOLOGIES = {
    "NCBITaxon": "ncbitaxon",
    "ENVO": "envo",
    "UBERON": "uberon",
    "MONDO": "mondo",
    "DOID": "doid",
    "CHEBI": "chebi",
    "GO": "go",
    "SO": "so",
    "ARO": "aro",
    "ECO": "eco",
    "FOODON": "foodon",
}
CURIE_RE = re.compile(r"\b(" + "|".join(ONTOLOGIES) + r"):(\d+)\b")


def iri(prefix: str, local: str) -> str:
    return f"{OBO}{prefix}_{local}"


def curie_of(term_iri: str) -> tuple[str, str] | None:
    if not term_iri.startswith(OBO):
        return None
    prefix, _, local = term_iri[len(OBO):].partition("_")
    return (prefix, local) if prefix in ONTOLOGIES else None


def get_json(url: str, retries: int = 4) -> dict:
    for attempt in range(retries):
        try:
            with urllib.request.urlopen(url, timeout=30) as r:
                return json.load(r)
        except Exception as e:  # noqa: BLE001
            if attempt == retries - 1:
                raise RuntimeError(f"OLS request failed: {url}: {e}") from e
            time.sleep(2 * (attempt + 1))
    return {}


def term_url(onto: str, term_iri: str, suffix: str = "") -> str:
    enc = urllib.parse.quote(urllib.parse.quote(term_iri, safe=""), safe="")
    return f"{OLS}/ontologies/{onto}/terms/{enc}{suffix}"


def parents(onto: str, term_iri: str) -> list[dict]:
    """Direct is_a parents (OLS 'parents' endpoint), across all result pages."""
    out, url = [], term_url(onto, term_iri, "/parents?size=200")
    while url:
        data = get_json(url)
        out.extend(data.get("_embedded", {}).get("terms", []))
        url = data.get("_links", {}).get("next", {}).get("href")
        time.sleep(0.2)
    return out


def used_terms() -> set[tuple[str, str]]:
    files = list((ROOT / "examples" / "valid").glob("*.yaml"))
    files += list((ROOT / "mappings" / "curated").glob("*.sssom.tsv"))
    terms = set()
    for f in files:
        terms.update(CURIE_RE.findall(f.read_text()))
    return terms


def main() -> int:
    seeds = used_terms()
    labels: dict[str, str] = {}
    edges: dict[str, set[tuple[str, str]]] = defaultdict(set)  # prefix -> (child, parent)
    seen: set[str] = set()
    queue = [iri(p, l) for p, l in sorted(seeds)]
    print(f"{len(queue)} seed terms", file=sys.stderr)

    while queue:
        child = queue.pop()
        if child in seen:
            continue
        seen.add(child)
        prefix, _ = curie_of(child)
        onto = ONTOLOGIES[prefix]
        try:
            if child not in labels:
                labels[child] = get_json(term_url(onto, child)).get("label", "")
            for p in parents(onto, child):
                p_iri = p["iri"]
                if curie_of(p_iri) is None:  # e.g. BFO roots, owl:Thing
                    continue
                labels.setdefault(p_iri, p.get("label", ""))
                edges[prefix].add((child, p_iri))
                queue.append(p_iri)
        except RuntimeError as e:
            print(f"WARN {e}", file=sys.stderr)

    OUT.mkdir(parents=True, exist_ok=True)
    by_prefix: dict[str, set[str]] = defaultdict(set)
    for t in seen:
        by_prefix[curie_of(t)[0]].add(t)
    for prefix, terms in sorted(by_prefix.items()):
        lines = [
            f"# Slim of {prefix}: is_a closure of terms used in examples/ and mappings/.",
            "# Generated by scripts/build_slims.py from EBI OLS4. Do not edit by hand.",
            "@prefix rdfs: <http://www.w3.org/2000/01/rdf-schema#> .",
            "",
        ]
        for t in sorted(terms):
            label = labels.get(t, "").replace("\\", "\\\\").replace('"', '\\"')
            lines.append(f'<{t}> rdfs:label "{label}" .')
        for c, p in sorted(edges[prefix]):
            lines.append(f"<{c}> rdfs:subClassOf <{p}> .")
        (OUT / f"{prefix.lower()}.ttl").write_text("\n".join(lines) + "\n")
        print(f"{prefix}: {len(terms)} terms, {len(edges[prefix])} edges", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
